const fs = require('fs');
const path = require('path');
const ts = require('typescript');

function walk(dir, exts) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const list = fs.readdirSync(dir);
  list.forEach(function(file) {
    file = path.resolve(dir, file);
    const stat = fs.statSync(file);
    if (stat && stat.isDirectory()) {
      results = results.concat(walk(file, exts));
    } else {
      for (const e of exts) if (file.endsWith(e)) results.push(file);
    }
  });
  return results;
}

const root = path.resolve(__dirname, '..', 'node_modules');
const files = walk(root, ['.d.ts', '.ts']);
let problems = 0;
let countWithRefs = 0;
for (const f of files) {
  try {
    const text = fs.readFileSync(f, 'utf8');
    const sf = ts.createSourceFile(f, text, ts.ScriptTarget.ESNext, /*setParentNodes*/ true);
    if (sf.referencedFiles && sf.referencedFiles.length) {
      countWithRefs++;
      sf.referencedFiles.forEach((r, i) => {
        if (!r || !r.fileName || typeof r.pos !== 'number' || typeof r.end !== 'number') {
          console.log('Malformed reference in', f, 'index', i, 'entry=', JSON.stringify(r));
          problems++;
        }
      });
    }
  } catch (e) {
    // ignore parse errors
  }
}
console.log('Scanned', files.length, 'files, found', countWithRefs, 'with referencedFiles.');
if (problems === 0) console.log('No malformed referencedFiles found in node_modules.');
else console.log('Found', problems, 'malformed referencedFiles entries in node_modules.');
